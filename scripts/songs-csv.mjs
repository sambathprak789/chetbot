// Pure CSV → SQL logic for the Khmer song list (no file access, so it can be unit-tested).

/** Parse CSV text (RFC 4180 quotes, CRLF or LF, optional UTF-8 BOM). */
export function parseCsv(text) {
  const src = text.replace(/^﻿/, "");
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (quoted) {
      if (c === '"' && src[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && src[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else field += c;
  }
  if (field !== "" || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((f) => f.trim() !== ""));
}

/**
 * Validate rows (Spec 5.4): title/artist not empty, moods from the allowed list,
 * no duplicate title+artist. Returns { songs, errors }.
 */
export function validateSongs(rows, allowedMoods) {
  const errors = [];
  const songs = [];
  const seen = new Map();
  const [header, ...body] = rows;
  const col = (name) => header?.findIndex((h) => h.trim().toLowerCase() === name) ?? -1;
  const iTitle = col("title");
  const iArtist = col("artist");
  const iMoods = col("moods");
  if (iTitle < 0 || iArtist < 0 || iMoods < 0) {
    return { songs, errors: ["Header must contain: title,artist,moods"] };
  }
  body.forEach((r, idx) => {
    const line = idx + 2; // 1-based, after header
    const title = (r[iTitle] ?? "").trim();
    const artist = (r[iArtist] ?? "").trim();
    const moods = (r[iMoods] ?? "")
      .split(/[;,|]/)
      .map((m) => m.trim().toLowerCase())
      .filter(Boolean);
    if (!title) errors.push(`line ${line}: title is empty`);
    if (!artist) errors.push(`line ${line}: artist is empty`);
    if (moods.length === 0) errors.push(`line ${line}: moods is empty`);
    const bad = moods.filter((m) => !allowedMoods.includes(m));
    if (bad.length) errors.push(`line ${line}: unknown mood(s) ${bad.join(", ")}`);
    const key = `${title.toLowerCase()}|${artist.toLowerCase()}`;
    if (title && artist && seen.has(key)) {
      errors.push(`line ${line}: duplicate of line ${seen.get(key)} (${title} — ${artist})`);
    }
    if (!seen.has(key)) seen.set(key, line);
    songs.push({ title, artist, moods: [...new Set(moods)].join(",") });
  });
  return { songs, errors };
}

const q = (s) => `'${s.replace(/'/g, "''")}'`;

/**
 * Build SQL that makes the songs table match the list:
 * listed songs are inserted or updated and set active = 1,
 * songs no longer in the list are kept but set active = 0 (Spec 5.3).
 */
export function buildSongsSql(songs) {
  const lines = [
    "-- GENERATED by scripts/build-songs.mjs from seed/songs.csv — do not edit by hand.",
    "UPDATE songs SET active = 0;",
  ];
  for (const s of songs) {
    lines.push(
      `INSERT INTO songs (title, artist, moods, active) VALUES (${q(s.title)}, ${q(s.artist)}, ${q(s.moods)}, 1) ` +
        `ON CONFLICT (title, artist) DO UPDATE SET moods = excluded.moods, active = 1;`,
    );
  }
  return lines.join("\n") + "\n";
}
